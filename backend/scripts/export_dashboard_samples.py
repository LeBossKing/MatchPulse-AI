"""Export reproducible, clearly illustrative Task 5 data from the mock workflow."""

import argparse
import json
from pathlib import Path
import sys

BACKEND_DIR = Path(__file__).resolve().parents[1]
ROOT = BACKEND_DIR.parent
sys.path.insert(0, str(BACKEND_DIR))

from app.api.matches import demo_events, demo_match  # noqa: E402
from app.models.insight import ProcessEventRequest, ProcessEventResponse  # noqa: E402
from app.services.demo_repository import load_demo_fixture  # noqa: E402
from app.services.providers import select_provider  # noqa: E402
from app.services.workflow import run_workflow  # noqa: E402

OUTPUT = ROOT / "frontend" / "src" / "data" / "dashboard-samples.ts"


def sample_document() -> dict:
    fixture = load_demo_fixture()
    responses = []
    for index, event in enumerate(fixture.events):
        for language in ("en", "fr"):
            for audience in ("analyst", "fan"):
                request = ProcessEventRequest(
                    match_id=fixture.match.match_id, event_id=event.event_id,
                    audience=audience, language=language,
                )
                result = run_workflow(fixture, index, request, select_provider("mock"))
                result.result_source = "example"
                for step in result.agent_trace:
                    step.duration_ms = 0
                    step.summary = (
                        "Illustrative mock output for UI development; "
                        "no agent executes in the browser."
                    )
                result.warnings[0] = (
                    "Exemple préchargé pour la démonstration ; aucun agent ni modèle n'est exécuté dans le navigateur."
                    if language == "fr" else
                    "Preloaded sample output; no agent or model executes in the browser."
                )
                # Revalidate after changing provenance and placeholders.
                result = ProcessEventResponse.model_validate(result.model_dump(mode="json"))
                responses.append(result.model_dump(mode="json"))
    return {
        "match": demo_match().model_dump(mode="json"),
        "events": demo_events().model_dump(mode="json"),
        "responses": responses,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the UI samples are stale.")
    args = parser.parse_args()
    content = (
        "// Generated by backend/scripts/export_dashboard_samples.py. Do not edit manually.\n"
        "// Illustrative data only: no agent or model runs in the browser.\n"
        "import type { DashboardSamples } from '../types/dashboard'\n\n"
        "export const dashboardSamples = "
        + json.dumps(sample_document(), ensure_ascii=False, indent=2)
        + " satisfies DashboardSamples\n"
    )
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            parser.exit(1, "Dashboard samples are stale. Run python scripts/export_dashboard_samples.py.\n")
        print("All 32 dashboard samples match the canonical fixture and mock workflow.")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(content, encoding="utf-8")
        print(f"Exported {OUTPUT.relative_to(ROOT)} (32 illustrative views).")


if __name__ == "__main__":
    main()
