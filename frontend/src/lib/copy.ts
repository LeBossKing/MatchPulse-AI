export function copy(language: Language) {
  return language === 'fr' ? fr : en
}

export function eventLabel(event: MatchEvent, language: Language): string {
  const t = copy(language)
  return event.event_type === 'pass'
    ? event.successful
      ? t.completed
      : t.unsuccessful
    : t[event.event_type]
}
